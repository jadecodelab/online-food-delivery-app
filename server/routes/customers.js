// routes/customers.js - /api/customers
// =====================================================================
const express = require("express");
const dao = require("../DAO");
const {
  optionalText,
  escapeLike,
  validateCustomer,
  idParam,
  NotFoundError,
} = require("../validators");

/** Read one customer by ID (returns undefined if not found). */
async function findCustomer(customerId) {
  const [row] = await dao.query(
    `SELECT CustomerID, FirstName, LastName, PhoneNumber, Email, Address
     FROM CUSTOMER WHERE CustomerID = ?`,
    [customerId]
  );
  return row;
}

const router = express.Router();

/**
 * GET /api/customers?search=
 * Search customers by full name, email, or phone number.
 *
 * LEFT JOIN with ORDERS so customers who have never ordered
 * still appear, with OrderCount = 0. COUNT(o.OrderID) counts only
 * matching orders because COUNT ignores NULLs.
 */
router.get("/", async (req, res) => {
  const search = optionalText(req.query.search, "Search keyword");

  const where = [];
  const params = [];

  if (search) {
    const pattern = `%${escapeLike(search)}%`;
    const conditions = [
      "CONCAT(c.FirstName, ' ', c.LastName) LIKE ?",
      "c.Email LIKE ?",
      "c.PhoneNumber LIKE ?",
    ];
    params.push(pattern, pattern, pattern);

    // Let "2175550101" match "217-555-0101": compare digits only
    const digits = search.replace(/\D/g, "");
    if (digits.length >= 3) {
      conditions.push("REPLACE(c.PhoneNumber, '-', '') LIKE ?");
      params.push(`%${digits}%`);
    }
    where.push("(" + conditions.join(" OR ") + ")");
  }

  const sql = `
    SELECT c.CustomerID, c.FirstName, c.LastName, c.Email, c.PhoneNumber, c.Address,
           COUNT(o.OrderID) AS OrderCount
    FROM CUSTOMER c
    LEFT JOIN ORDERS o ON o.CustomerID = c.CustomerID
    ${where.length ? "WHERE " + where.join(" AND ") : ""}
    GROUP BY c.CustomerID, c.FirstName, c.LastName, c.Email, c.PhoneNumber, c.Address
    ORDER BY c.LastName, c.FirstName`;

  res.json(await dao.query(sql, params));
});

/**
 * POST /api/customers
 * Body: { firstName, lastName, phoneNumber, email, address }
 * Add a new customer.
 *
 * 1) validateCustomer() checks required fields, lengths, and formats (-> 400).
 * 2) INSERT with ? placeholders. CustomerID is generated by AUTO_INCREMENT.
 * 3) A duplicate email is rejected by the UNIQUE constraint (MySQL error 1062);
 *    errors.js turns it into a 409 "already exists" message. We rely on the
 *    database for this instead of checking first, because only the database
 *    can guarantee uniqueness when two requests arrive at the same time.
 * 4) Read the row back from MySQL so the response shows what was saved.
 */
router.post("/", async (req, res) => {
  const c = validateCustomer(req.body);

  const result = await dao.query(
    `INSERT INTO CUSTOMER (FirstName, LastName, PhoneNumber, Email, Address)
     VALUES (?, ?, ?, ?, ?)`,
    [c.firstName, c.lastName, c.phoneNumber, c.email, c.address]
  );

  const saved = await findCustomer(result.insertId);

  res.status(201).json({
    message: `Customer ${saved.FirstName} ${saved.LastName} was added (ID ${saved.CustomerID}).`,
    customer: saved,
  });
});

/**
 * GET /api/customers/:id
 * One customer, read fresh from MySQL (used to fill the Edit form).
 */
router.get("/:id", async (req, res) => {
  const customerId = idParam(req.params.id, "Customer ID");
  const customer = await findCustomer(customerId);
  if (!customer) throw new NotFoundError(`Customer #${customerId} was not found.`);
  res.json(customer);
});

/**
 * PUT /api/customers/:id
 * Body: { firstName, lastName, phoneNumber, email, address }
 * Update ONE existing customer.
 *
 * - Same validation as insert (validateCustomer).
 * - WHERE CustomerID = ? targets only the intended record (primary key),
 *   so exactly one row can change.
 * - Changing the email to one another customer uses -> UNIQUE constraint
 *   (error 1062) -> 409 "already exists".
 * - Unknown ID -> 404. No actual change -> success with "No changes were made".
 */
router.put("/:id", async (req, res) => {
  const customerId = idParam(req.params.id, "Customer ID");
  const c = validateCustomer(req.body);

  const before = await findCustomer(customerId);
  if (!before) throw new NotFoundError(`Customer #${customerId} was not found.`);

  const unchanged =
    before.FirstName === c.firstName &&
    before.LastName === c.lastName &&
    before.PhoneNumber === c.phoneNumber &&
    before.Email === c.email &&
    before.Address === c.address;

  if (!unchanged) {
    await dao.query(
      `UPDATE CUSTOMER
       SET FirstName = ?, LastName = ?, PhoneNumber = ?, Email = ?, Address = ?
       WHERE CustomerID = ?`,
      [c.firstName, c.lastName, c.phoneNumber, c.email, c.address, customerId]
    );
  }

  const saved = await findCustomer(customerId);
  res.json({
    message: unchanged
      ? `No changes were made to ${saved.FirstName} ${saved.LastName}.`
      : `Customer ${saved.FirstName} ${saved.LastName} (ID ${saved.CustomerID}) was updated.`,
    customer: saved,
    changed: !unchanged,
  });
});

module.exports = router;
